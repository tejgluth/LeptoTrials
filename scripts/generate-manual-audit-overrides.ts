import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const REVIEW_DIR = join(process.cwd(), 'audit', 'manual-review')
const OUTPUT_FILE = join(process.cwd(), 'src', 'utils', 'manualAuditOverrides.ts')

type ReviewEntry = {
  nctId: string
  briefTitle: string
  siteEligible: boolean | null
  tumorLabels: string[]
  confidence: string
  rationale: string
  minimumAge?: string
}

type ReviewFile = {
  reviews: ReviewEntry[]
}

async function main() {
  const manifest = JSON.parse(await readFile(join(REVIEW_DIR, 'classification-decisions.json'), 'utf8')) as ReviewFile & { reviewedOn: string }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(manifest.reviewedOn)) throw new Error('Missing review date')
  const reviews = manifest.reviews
  const seen = new Set<string>()
  const labels = new Set(['LUNG', 'BREAST', 'MELANOMA', 'GBM', 'OTHER_SOLID'])
  for (const review of reviews) {
    if (!/^NCT\d{8}$/.test(review.nctId) || seen.has(review.nctId) ||
        typeof review.siteEligible !== 'boolean' ||
        review.tumorLabels.some((label) => !labels.has(label)) ||
        (!review.siteEligible && review.tumorLabels.length) ||
        (review.minimumAge !== undefined &&
         (!/^\d+(?:\.\d+)? Years$/.test(review.minimumAge) ||
          Number.parseFloat(review.minimumAge) > 120))) {
      throw new Error(`Invalid or duplicate review: ${review.nctId}`)
    }
    seen.add(review.nctId)
  }

  const incomplete = reviews.filter(
    (review) => review.siteEligible === null || !review.confidence || !review.rationale
  )
  if (incomplete.length > 0) {
    throw new Error(`Manual audit overrides cannot be generated; ${incomplete.length} reviews are incomplete`)
  }

  const sorted = [...reviews].sort((a, b) => a.nctId.localeCompare(b.nctId))

  const lines: string[] = []
  lines.push("import type { TumorTypeFilter } from '../types/trial'")
  lines.push('')
  lines.push('export type ManualAuditOverride = {')
  lines.push('  siteEligible: boolean')
  lines.push("  tumorLabels: Array<Exclude<TumorTypeFilter, 'any'>>")
  lines.push('  /** Source-reviewed correction when structured registry age conflicts with explicit criteria. */')
  lines.push('  minimumAge?: string')
  lines.push('}')
  lines.push('')
  lines.push(`export const MANUAL_AUDIT_REVIEWED_ON = '${manifest.reviewedOn}'`)
  lines.push('')
  lines.push('// Generated by npm run generate:manual-audit-overrides; edit audit/manual-review/classification-decisions.json.')
  lines.push('export const MANUAL_AUDIT_OVERRIDES: Record<string, ManualAuditOverride> = {')

  for (const review of sorted) {
    const tumorLabels = review.tumorLabels
      .map((label) => `'${label}'`)
      .join(', ')
    lines.push(
      `  '${review.nctId}': { siteEligible: ${review.siteEligible ? 'true' : 'false'}, tumorLabels: [${tumorLabels}]${review.minimumAge ? `, minimumAge: '${review.minimumAge}'` : ''} },`
    )
  }

  lines.push('}')
  lines.push('')
  lines.push('export function getManualAuditOverride(nctId: string): ManualAuditOverride | undefined {')
  lines.push('  return MANUAL_AUDIT_OVERRIDES[nctId]')
  lines.push('}')
  lines.push('')

  await writeFile(OUTPUT_FILE, `${lines.join('\n').trimEnd()}\n`)
  console.log(`Wrote ${sorted.length} manual audit overrides to ${OUTPUT_FILE}`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack ?? error.message : String(error))
  process.exitCode = 1
})
